function definition(
  name: string,
  description: string,
  scope: string,
  properties: Record<string, unknown>,
  required: string[],
  options: { read?: boolean; files?: boolean; external?: boolean } = {},
) {
  const schemes = [{ type: "oauth2", scopes: [scope] }];
  return {
    name,
    description,
    inputSchema: {
      type: "object",
      properties,
      required,
      additionalProperties: false,
    },
    annotations: {
      readOnlyHint: !!options.read,
      destructiveHint: !options.read,
      idempotentHint: true,
      openWorldHint: !!options.external,
    },
    securitySchemes: schemes,
    _meta: {
      securitySchemes: schemes,
      ...(options.files ? { "openai/fileParams": ["files"] } : {}),
    },
  };
}
